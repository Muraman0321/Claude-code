-- Glider Flight Analyzer — Supabase schema
--
-- One-time setup:
--   1. Create a new Supabase project (free plan).
--   2. Open SQL Editor, paste this whole file, click Run.
--   3. Open Storage, create a bucket named "fixes" (private).
--   4. In Project Settings → API, copy the project URL and the anon key,
--      and set them as Render Static Site env vars:
--        VITE_SUPABASE_URL=https://xxxxx.supabase.co
--        VITE_SUPABASE_ANON_KEY=eyJhbGci...
--
-- Re-running this script is safe (idempotent).

create extension if not exists "pgcrypto";

create table if not exists flights (
  id          bigint generated by default as identity primary key,
  owner       uuid not null references auth.users(id) on delete cascade,
  filename    text not null,
  pilot       text not null,
  aircraft    text not null,
  remarks     text,
  flight_date date not null,
  started_at  timestamptz,
  ended_at    timestamptz,
  start_latitude  double precision,
  start_longitude double precision,
  summary     jsonb not null default '{}'::jsonb,
  weather     jsonb,
  raw_igc     text,
  created_at  timestamptz default now()
);

create unique index if not exists flights_owner_filename_pilot_uniq
  on flights (owner, lower(filename), lower(pilot));

create index if not exists flights_owner_date_idx
  on flights (owner, flight_date desc);

create table if not exists thermals (
  id             bigint generated by default as identity primary key,
  flight_id      bigint not null references flights(id) on delete cascade,
  owner          uuid not null references auth.users(id) on delete cascade,
  start_time     timestamptz not null,
  end_time       timestamptz not null,
  duration_s     double precision not null,
  altitude_gain_m double precision not null,
  avg_climb_rate_ms double precision not null,
  center_lat     double precision not null,
  center_lon     double precision not null,
  start_lat      double precision,
  start_lon      double precision,
  end_lat        double precision,
  end_lon        double precision
);

create index if not exists thermals_owner_flight_idx
  on thermals (owner, flight_id);

create index if not exists thermals_owner_start_idx
  on thermals (owner, start_time);

-- Row-Level Security: every row is owned by exactly one auth user.
alter table flights  enable row level security;
alter table thermals enable row level security;

drop policy if exists "flights_owner_all" on flights;
create policy "flights_owner_all" on flights
  for all using (owner = auth.uid()) with check (owner = auth.uid());

drop policy if exists "thermals_owner_all" on thermals;
create policy "thermals_owner_all" on thermals
  for all using (owner = auth.uid()) with check (owner = auth.uid());

-- Storage RLS for the "fixes" bucket.
-- Each flight's downsampled GPS-fix JSON is stored at: {owner_uuid}/{flight_id}.json
-- The first path segment must equal auth.uid() so users can only read/write their own files.
drop policy if exists "fixes_owner_read"   on storage.objects;
drop policy if exists "fixes_owner_write"  on storage.objects;
drop policy if exists "fixes_owner_update" on storage.objects;
drop policy if exists "fixes_owner_delete" on storage.objects;

create policy "fixes_owner_read" on storage.objects
  for select using (
    bucket_id = 'fixes' and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy "fixes_owner_write" on storage.objects
  for insert with check (
    bucket_id = 'fixes' and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy "fixes_owner_update" on storage.objects
  for update using (
    bucket_id = 'fixes' and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy "fixes_owner_delete" on storage.objects
  for delete using (
    bucket_id = 'fixes' and (storage.foldername(name))[1] = auth.uid()::text
  );
